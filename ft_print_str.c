#include "ft_printf.h"

int	ft_print_str(char *n)
{
	int	i;

	i = 0;
	if (!n)
	{
		write(1, "(null)", 6);
		return(6);
	}
	while(n[i])
	{
		write(1, &n[i], 1);
		i++;
	}
	return(i);
}